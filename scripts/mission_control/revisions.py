import json
from pathlib import Path


def revision_diff(parent, proposed):
    from .publication import digest
    changes = []
    for field in sorted(set(parent) | set(proposed)):
        if field == 'steps':continue
        if parent.get(field) != proposed.get(field):
            changes.append({'field': field, 'before': parent.get(field), 'after': proposed.get(field)})
    old = {step['id']: step for step in parent['steps']}
    new = {step['id']: step for step in proposed['steps']}
    for identifier in sorted(set(old) | set(new)):
        if old.get(identifier) != new.get(identifier):
            changes.append({'step': identifier, 'before': old.get(identifier), 'after': new.get(identifier)})
    if [s['id'] for s in parent['steps']] != [s['id'] for s in proposed['steps']]:
        changes.append({'field': 'step_order', 'before': list(old), 'after': list(new)})
    return {'parent_contract_hash': digest(parent), 'proposed_contract_hash': digest(proposed), 'changes': changes}


def publish_revision(root, contract, state, args):
    from .publication import digest, now, publish_migration
    from .contract import validate_known_fields
    from .validation import validate
    if not args.destination or not args.contract or not args.reason or not args.reason.strip():
        raise ValueError('revise requires --contract, new --destination and nonblank --reason')
    proposed = json.loads(Path(args.contract).read_text(encoding='utf-8-sig'))
    validate(proposed)
    validate_known_fields(proposed)
    if proposed['schema_version'] != 3:raise ValueError('new revisions require schema 3')
    if 'revision' in proposed:raise ValueError('revision lineage is generated by revise, not supplied in the proposed contract')
    parent_revision = contract.get('revision', {})
    if not isinstance(parent_revision, dict) or type(parent_revision.get('number', 0)) is not int:
        raise ValueError('invalid parent revision metadata')
    changes = revision_diff(contract, proposed)
    proposed['revision'] = {'number': parent_revision.get('number', 0) + 1,
                            'parent_contract_hash': digest(contract),
                            'parent_checkpoint_hash': digest(state),
                            'parent_mission': str(root.resolve()), 'reason': args.reason,
                            'timestamp': now(), 'changes': changes['changes']}
    validate(proposed)
    publish_migration(Path(args.destination), proposed,
                      {'parent-contract.json': contract, 'parent-progress.json': state}, backup_dir='lineage')
    print(json.dumps({'destination': str(Path(args.destination).absolute()), 'revision': proposed['revision']}, indent=2))


def validate_advanced_state(state, contract):
    from .approvals import valid_digest
    from .contract import text_list
    from .journal import validate_journal
    from .quality import evidence_kinds
    if contract['schema_version'] != 3:return
    reviews = state.get('acceptance_reviews', {})
    if not isinstance(reviews, dict):raise ValueError('invalid acceptance review mapping')
    ids = {item['id'] for item in contract['acceptance']}
    for identifier, review in reviews.items():
        if (identifier not in ids or not isinstance(review, dict)
                or review.get('verdict') not in ('supported', 'unmet', 'unverified')
                or not isinstance(review.get('rationale'), str) or not review['rationale'].strip()
                or not isinstance(review.get('timestamp'), str) or not valid_digest(review.get('signature'))):
            raise ValueError('invalid acceptance review')
        text_list(review.get('evidence_refs'), 'stored evidence references')
        evidence_kinds(review.get('evidence_kinds',[]))
    for entry in state['steps'].values():
        if 'recovery_required' in entry and type(entry['recovery_required']) is not bool:
            raise ValueError('invalid recovery_required flag')
        if 'effect_baseline' in entry and not isinstance(entry['effect_baseline'], dict):
            raise ValueError('invalid effect baseline')
        if 'verified_artifacts' in entry and not isinstance(entry['verified_artifacts'], dict):
            raise ValueError('invalid verification artifact receipt')
        if 'recovery_history' in entry and not isinstance(entry['recovery_history'], list):
            raise ValueError('invalid recovery history')
    validate_journal(state, contract)

